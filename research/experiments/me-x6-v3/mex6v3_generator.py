"""ME-X6 V3 generator: ROLE-COVERAGE COMPLETION of the frozen V1 generator.

V2 found that a learned capacity-matched untyped comparator (`B8`, = greedy `B6`)
ties M 1400/1400 with the vector `formal_artifacts +1, replications_passed +1,
retractions -1, independent_rederivations +1` and every other channel zeroed.

The four validation channels that vector zeroes -- `downstream_reuse`,
`corrections`, `solution_cost`, `replications_failed` -- are exactly the four of
M's eight declared roles (`mex6_arms.TYPED_SIGNS`) that NO V1 stratum exercises as
a lone capability carrier.  Read from the frozen V1 generator, not asserted:

  * `replications_failed` never moves in any V1 stratum;
  * `corrections` moves only inside `I4_RETRACTED_WORK`, alongside a retraction
    rise three times larger and every DEFAULT carrier rising;
  * `solution_cost` and `downstream_reuse` move only as part of the
    DEFAULT_CARRIERS block, never alone.

(`mex6v3_run.role_coverage_census` recomputes this from generated instances and
the selftest asserts it, so the premise is measured rather than quoted.)

So V2's fitter dropped the roles the development split never exercised in
isolation.  V3 adds the four missing lone-carrier strata -- declared here, before
any outcome exists -- and asks whether the a-priori typed assignment is
load-bearing under ROLE-COVERAGE SHIFT.

Nothing here modifies V1.  V1 strata are generated by V1's own `build_window`,
imported read-only, so a V3 instance of a V1 stratum is exactly what V1's generator
would emit for the same seed (asserted in the tests).  Only the four new strata
have V3-authored channel signatures, and each is derived from the protocol
semantics recorded in `mex6_arms.TYPED_SIGNS`' comments and the `mex6_model`
docstrings, never from any arm's behaviour.
"""
from __future__ import annotations

import random
import sys
from pathlib import Path

_V1 = Path(__file__).resolve().parent.parent / "me-x6"
if str(_V1) not in sys.path:
    sys.path.insert(0, str(_V1))

from mex6_generator import (  # noqa: E402  (V1, read-only)
    CAPABILITY_CARRIERS,
    DEFAULT_CARRIERS,
    FIT_LEN,
    HORIZON,
    MAX_ATTEMPTS,
    SCALE_PARAMS,
    STRATA,
    _levels,
    build_window,
    instance_seed,
    sha256_text,
)
from mex6_model import (  # noqa: E402
    ACTIVITY_CHANNELS,
    CAPABILITY_COORDS,
    CHANNELS,
    FALL,
    FLAT,
    LATENT_COORDS,
    RISE,
    SCALES,
    VALIDATION_CHANNELS,
    FieldWindow,
    Instance,
    Period,
)
from mex6_oracle import oracle  # noqa: E402

# ---- the four role-completion strata: (capability direction, activity direction) --
# Declared before any outcome exists.  Each exercises ONE of M's declared roles
# that V1 never exercised alone, with the (capability, activity) effect derived
# from the protocol semantics:
#
#   I11_SILENT_CORRECTION_EROSION  corrections RISE alone; every ordinary validated
#       channel FLAT; activity FLAT.  A correction qualifies a claim without
#       withdrawing it (TYPED_SIGNS: corrections -1, retractions -2), so validated
#       reach and verification depth (R, V) FALL while nothing else moves.
#   I12_FAILED_REPLICATION_WAVE    replications_failed RISE alone; activity RISE,
#       because the failed replications are themselves publications; capability
#       FALLS (a failed replication is invalidation: TYPED_SIGNS -1).
#   I13_COST_COLLAPSE              solution_cost FALL alone; activity FLAT.  The same
#       validated result reached more cheaply is a capability gain (validation
#       target V4; TYPED_SIGNS: solution_cost -1, mex6_generator "cost is
#       inverted").  Capability RISES.
#   I14_REUSE_ONLY_GAIN            downstream_reuse RISE alone; activity FLAT.  Reuse
#       downstream is independently checkable evidence (TYPED_SIGNS +1), so
#       capability RISES.
NEW_STRATA: dict[str, tuple[str, str]] = {
    "I11_SILENT_CORRECTION_EROSION": (FALL, FLAT),
    "I12_FAILED_REPLICATION_WAVE": (FALL, RISE),
    "I13_COST_COLLAPSE": (RISE, FLAT),
    "I14_REUSE_ONLY_GAIN": (RISE, FLAT),
}
HELD_OUT_STRATA: tuple[str, ...] = tuple(NEW_STRATA)

# The lone validated channel each new stratum moves, and the direction it moves in.
# This is the declared channel signature the generator-validity check recomputes
# against (never a count).
LONE_CARRIER: dict[str, tuple[str, str]] = {
    "I11_SILENT_CORRECTION_EROSION": ("corrections", RISE),
    "I12_FAILED_REPLICATION_WAVE": ("replications_failed", RISE),
    "I13_COST_COLLAPSE": ("solution_cost", FALL),
    "I14_REUSE_ONLY_GAIN": ("downstream_reuse", RISE),
}

# STRATA_V3 = V1 STRATA (in V1's order) followed by the four new strata.  An
# ordered dict, and CELLS_V3 an ordered tuple: no RNG draw in this module is ever
# ordered by an unordered container (NONREPRODUCIBLE_FROZEN_ARTIFACT guard).
STRATA_V3: dict[str, tuple[str, str]] = {**STRATA, **NEW_STRATA}
assert len(STRATA_V3) == len(STRATA) + len(NEW_STRATA), "a new stratum collides with a V1 name"
CELLS_V3: tuple[tuple[str, str], ...] = tuple((s, sc) for s in STRATA_V3 for sc in SCALES)
V1_STRATA: tuple[str, ...] = tuple(STRATA)

# Role-coverage ledger: for each of M's eight declared roles, the stratum that
# exercises it as a lone carrier.  Four come from V1 (retractions co-moves with
# corrections inside I4, recorded as such); four are the completion above.
ROLE_LONE_CARRIER_STRATUM: dict[str, str] = {
    "formal_artifacts": "X6I7_ONE_BREAKTHROUGH",
    "replications_passed": "I9_DELAYED_VALIDATION",
    "independent_rederivations": "I10_INDEPENDENT_REDISCOVERY",
    "retractions": "I4_RETRACTED_WORK",      # corrections co-move (x1 against x3)
    "corrections": "I11_SILENT_CORRECTION_EROSION",
    "replications_failed": "I12_FAILED_REPLICATION_WAVE",
    "solution_cost": "I13_COST_COLLAPSE",
    "downstream_reuse": "I14_REUSE_ONLY_GAIN",
}


def declared_channel_signature(stratum: str) -> dict[str, str]:
    """Every channel's declared direction for a NEW stratum (all 16 channels)."""
    cap_dir, act_dir = NEW_STRATA[stratum]
    carrier, cdir = LONE_CARRIER[stratum]
    sig = {c: FLAT for c in CHANNELS}
    for c in ACTIVITY_CHANNELS:
        sig[c] = act_dir
    sig[carrier] = cdir
    return sig


def build_window_v3(rng: random.Random, stratum: str, scale: str, window_id: str) -> FieldWindow:
    """V1 strata go through V1's own `build_window`, untouched.  The four new strata
    draw their structural quantities in exactly V1's order (step, onset, channel
    bases in CHANNELS order, latent bases in LATENT_COORDS order)."""
    if stratum in STRATA:
        return build_window(rng, stratum, scale, window_id)
    if stratum not in NEW_STRATA:
        raise KeyError(stratum)
    cap_dir, act_dir = NEW_STRATA[stratum]
    n = FIT_LEN + HORIZON
    par = SCALE_PARAMS[scale]
    step = rng.randrange(*par["step"])
    onset = rng.randrange(FIT_LEN // 2, FIT_LEN)
    bases = {c: rng.randrange(*par["base"]) for c in CHANNELS}
    lat_bases = {c: rng.randrange(*par["base"]) for c in LATENT_COORDS}
    sig = declared_channel_signature(stratum)
    ch: dict[str, list[int]] = {}
    for name in CHANNELS:
        d = sig[name]
        ch[name] = _levels(d, n, bases[name], step if d != FLAT else 0, onset)

    # --- the latent trajectory (never shown to any arm), V1's form ---------------
    lat: dict[str, list[int]] = {}
    lat["R"] = _levels(cap_dir, n, lat_bases["R"], step, onset)
    lat["V"] = _levels(cap_dir, n, lat_bases["V"], step, onset)
    lat["D"] = _levels(FLAT, n, lat_bases["D"], 0, onset)
    lat["T"] = _levels(cap_dir, n, lat_bases["T"], max(1, step // 2), onset)
    lat["G"] = _levels(FLAT, n, lat_bases["G"], 0, onset)
    lat["U"] = _levels(FLAT, n, lat_bases["U"], 0, onset)
    lat["C"] = _levels({RISE: FALL, FALL: RISE, FLAT: FLAT}[cap_dir], n, lat_bases["C"], step, onset)
    lat["E"] = _levels(FLAT, n, lat_bases["E"], 0, onset)

    periods = tuple(
        Period(index=i,
               latent={k: lat[k][i] for k in LATENT_COORDS},
               channels={k: ch[k][i] for k in CHANNELS})
        for i in range(n)
    )
    return FieldWindow(window_id=window_id, scale=scale, fit_len=FIT_LEN,
                       horizon=HORIZON, periods=periods)


# ---- generator validity: independent recomputation against the DECLARED effect ----

def expected_effect_v3(stratum: str) -> tuple[str, str]:
    return STRATA_V3[stratum]


def planter_agrees_v3(w: FieldWindow, stratum: str) -> tuple[bool, str]:
    """V1's `planter_agrees`, extended to STRATA_V3.  The oracle verdict recomputed
    from the planted latent trajectory must equal the DECLARED (capability,
    activity) effect exactly -- never a count."""
    want_cap, want_act = expected_effect_v3(stratum)
    got = oracle(w)
    if got.capability != want_cap:
        return False, f"{stratum}: capability {got.capability} != declared {want_cap}"
    if got.activity != want_act:
        return False, f"{stratum}: activity {got.activity} != declared {want_act}"
    return True, ""


def _half_dir(w: FieldWindow, channel: str) -> str:
    h = w.fit_len // 2
    a = sum(p.channels[channel] for p in w.fit_periods[:h])
    b = sum(p.channels[channel] for p in w.fit_periods[h:])
    return RISE if b > a else (FALL if b < a else FLAT)


def channel_signature_agrees(w: FieldWindow, stratum: str) -> tuple[bool, str]:
    """For a NEW stratum: every one of the 16 channels moves exactly as declared.
    This is what makes the stratum a LONE-carrier stratum in fact and not in name.
    For a V1 stratum this check is not defined (V1 declares carriers, not full
    signatures) and returns (True, 'V1_STRATUM_NOT_CHECKED')."""
    if stratum not in NEW_STRATA:
        return True, "V1_STRATUM_NOT_CHECKED"
    sig = declared_channel_signature(stratum)
    for c in CHANNELS:
        got = _half_dir(w, c)
        if got != sig[c]:
            return False, f"{stratum}: {c} moves {got}, declared {sig[c]}"
    return True, ""


def generate_instance_v3(prefix: str, split_seed: str, stratum: str, scale: str, index: int) -> Instance:
    rng = random.Random(instance_seed(split_seed, stratum, scale, index))
    iid = f"{prefix}-{stratum}-{scale}-{index:04d}"
    why = ""
    for _ in range(MAX_ATTEMPTS):
        w = build_window_v3(random.Random(rng.randrange(2**62)), stratum, scale,
                            window_id=f"fw-{sha256_text(iid)[:16]}")
        ok, why = planter_agrees_v3(w, stratum)
        if ok:
            ok2, why2 = channel_signature_agrees(w, stratum)
            if not ok2:
                raise RuntimeError(f"declared channel signature violated for {iid}: {why2}")
            return Instance(window=w, stratum=stratum, scale=scale, instance_id=iid,
                            facts=(("planted_capability", STRATA_V3[stratum][0]),
                                   ("planted_activity", STRATA_V3[stratum][1])))
    raise RuntimeError(f"generator could not satisfy the planter check for {iid}: {why}")


def generate_split_v3(prefix: str, split_seed: str, per_cell: int,
                      strata: tuple[str, ...] | None = None) -> list[Instance]:
    cells = CELLS_V3 if strata is None else tuple((s, sc) for s in strata for sc in SCALES)
    return [generate_instance_v3(prefix, split_seed, stratum, scale, i)
            for stratum, scale in cells
            for i in range(per_cell)]


# ---- the role-coverage census, recomputed from instances ---------------------------

def validation_movers(w: FieldWindow) -> tuple[str, ...]:
    """Which validation channels move (in CHANNELS order) over the fit halves."""
    return tuple(c for c in VALIDATION_CHANNELS if _half_dir(w, c) != FLAT)


